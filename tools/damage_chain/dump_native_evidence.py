#!/usr/bin/env python3
"""Extract damage-chain-relevant declarations from both tracked NTE dumps.

This script refuses Git LFS pointer text; the real objects must be materialized first.
"""
from __future__ import annotations

import argparse
import difflib
import hashlib
from pathlib import Path

VERSIONS = ("5.6.1", "5.6.1-new")
SDK_FILES = (
    "CppSDK/SDK/HTGame_classes.hpp",
    "CppSDK/SDK/HTGame_structs.hpp",
    "CppSDK/SDK/HTGame_parameters.hpp",
    "CppSDK/SDK/GameplayAbilities_structs.hpp",
    "GObjects-Dump.txt",
)

BLOCKS = {
    "FGameplayEventData": ("CppSDK/SDK/GameplayAbilities_structs.hpp",
        "// ScriptStruct GameplayAbilities.GameplayEventData",
        "DUMPER7_ASSERTS_FGameplayEventData;"),
    "FHTDamageEvent": ("CppSDK/SDK/HTGame_structs.hpp",
        "// ScriptStruct HTGame.HTDamageEvent", "DUMPER7_ASSERTS_FHTDamageEvent;"),
    "FBufferData": ("CppSDK/SDK/HTGame_structs.hpp",
        "// ScriptStruct HTGame.BufferData", "DUMPER7_ASSERTS_FBufferData;"),
    "FHTGameplayEffectContainer": ("CppSDK/SDK/HTGame_structs.hpp",
        "// ScriptStruct HTGame.HTGameplayEffectContainer", "DUMPER7_ASSERTS_FHTGameplayEffectContainer;"),
    "FSpawnDamageTriggerActor": ("CppSDK/SDK/HTGame_structs.hpp",
        "// ScriptStruct HTGame.SpawnDamageTriggerActor", "DUMPER7_ASSERTS_FSpawnDamageTriggerActor;"),
    "FSpawnDamageTriggerActorArray": ("CppSDK/SDK/HTGame_structs.hpp",
        "// ScriptStruct HTGame.SpawnDamageTriggerActorArray", "DUMPER7_ASSERTS_FSpawnDamageTriggerActorArray;"),
    "FDamageTriggerActorStaticData": ("CppSDK/SDK/HTGame_structs.hpp",
        "// ScriptStruct HTGame.DamageTriggerActorStaticData", "DUMPER7_ASSERTS_FDamageTriggerActorStaticData;"),
    "UHTAbilitySystemComponent": ("CppSDK/SDK/HTGame_classes.hpp",
        "// Class HTGame.HTAbilitySystemComponent", "DUMPER7_ASSERTS_UHTAbilitySystemComponent;"),
    "AHTAbilityCharacter": ("CppSDK/SDK/HTGame_classes.hpp",
        "// Class HTGame.HTAbilityCharacter", "DUMPER7_ASSERTS_AHTAbilityCharacter;"),
    "AHTAbilitySpawnActor": ("CppSDK/SDK/HTGame_classes.hpp",
        "// Class HTGame.HTAbilitySpawnActor", "DUMPER7_ASSERTS_AHTAbilitySpawnActor;"),
    "ADamageTriggerActor": ("CppSDK/SDK/HTGame_classes.hpp",
        "// Class HTGame.DamageTriggerActor", "DUMPER7_ASSERTS_ADamageTriggerActor;"),
    "UHTAbilitySpawnDamageTriggerActor": ("CppSDK/SDK/HTGame_classes.hpp",
        "// Class HTGame.HTAbilitySpawnDamageTriggerActor",
        "DUMPER7_ASSERTS_UHTAbilitySpawnDamageTriggerActor;"),
    "K2_ApplyGameEffectWithClassByActor": ("CppSDK/SDK/HTGame_parameters.hpp",
        "struct HTAbilitySystemComponent_K2_ApplyGameEffectWithClassByActor",
        "DUMPER7_ASSERTS_HTAbilitySystemComponent_K2_ApplyGameEffectWithClassByActor;"),
    "K2_ApplyGameplayEffectToTargetWithClass": ("CppSDK/SDK/HTGame_parameters.hpp",
        "struct HTAbilitySystemComponent_K2_ApplyGameplayEffectToTargetWithClass",
        "DUMPER7_ASSERTS_HTAbilitySystemComponent_K2_ApplyGameplayEffectToTargetWithClass;"),
    "HTAbilitySpawnActor_OverrideEffectContainer": ("CppSDK/SDK/HTGame_parameters.hpp",
        "struct HTAbilitySpawnActor_OverrideEffectContainer",
        "DUMPER7_ASSERTS_HTAbilitySpawnActor_OverrideEffectContainer;"),
    "HTAbilityCharacter_OnDamaged": ("CppSDK/SDK/HTGame_parameters.hpp",
        "struct HTAbilityCharacter_OnDamaged", "DUMPER7_ASSERTS_HTAbilityCharacter_OnDamaged;"),
}

OBJECT_QUERIES = (
    "HTAbilitySystemComponent.K2_ApplyGameEffectWithClassByActor",
    "HTAbilitySystemComponent.K2_ApplyGameplayEffectToTargetWithClass",
    "HTAbilityCharacter.CharacterOnDamaged",
    "HTAbilityCharacter.OnDamaged",
    "HTAbilitySpawnDamageTriggerActor",
    "HTAbilitySpawnActor.OverrideEffectContainer",
    "DamageTriggerActor.K2_OnTriggerPeriodGamePlayEffect",
    "DamageTriggerActor.StartTriggerGamePlayEffect",
    "HTGATargetType_UseEventData",
    "DamageTriggerActor",
)

def block(text: str, start_marker: str, end_marker: str) -> str:
    start = text.find(start_marker)
    if start < 0:
        return f"[NOT FOUND: start marker {start_marker!r}]"
    end = text.find(end_marker, start)
    if end < 0:
        return f"[NOT FOUND: end marker {end_marker!r} after byte {start}]"
    return text[start:end + len(end_marker)]

def read_real(path: Path) -> bytes:
    raw = path.read_bytes()
    if raw.startswith(b"version https://git-lfs.github.com/spec/v1"):
        raise RuntimeError(f"Git LFS pointer was not materialized: {path}")
    return raw

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=Path, help="root containing both dump folders")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    root = args.root.resolve()
    loaded: dict[str, dict[str, str]] = {}
    report: list[str] = [
        "# NTE native damage evidence: 5.6.1 vs 5.6.1-new",
        "",
        "Generated by extracting the repository's materialized Git LFS objects. This is evidence extraction, not proof that any candidate function is safe to call.",
        "",
    ]

    for version in VERSIONS:
        report += [f"## Dump {version}", ""]
        loaded[version] = {}
        for rel in SDK_FILES:
            p = root / version / rel
            if not p.is_file():
                report += [f"- {rel}: MISSING", ""]
                continue
            raw = read_real(p)
            loaded[version][rel] = raw.decode("utf-8-sig", errors="replace")
            report.append(
                f"- {rel}: {len(raw):,} bytes; SHA-256 {hashlib.sha256(raw).hexdigest()}")
        report.append("")

        for label, (rel, start_marker, end_marker) in BLOCKS.items():
            text = loaded[version].get(rel)
            if text is None:
                continue
            extracted = block(text, start_marker, end_marker)
            report += [f"### {label}", "", chr(96) * 3 + "cpp",
                       extracted.rstrip(), chr(96) * 3, ""]

        gob = loaded[version].get("GObjects-Dump.txt")
        if gob:
            report += ["### GObjects index hits", ""]
            lines = gob.splitlines()
            for query in OBJECT_QUERIES:
                found = [f"{i + 1}: {line.strip()}" for i, line in enumerate(lines)
                         if query.casefold() in line.casefold()]
                report.append(f"{query} — {len(found)} matching line(s)")
                report.extend(f"- {line}" for line in found[:20])
                if len(found) > 20:
                    report.append(f"- ... {len(found) - 20} additional matching line(s) omitted")
                report.append("")
        else:
            report += ["### GObjects index hits", "", "GObjects-Dump.txt was not materialized.", ""]

    report += ["## Focused declaration diffs", ""]
    for label, (rel, start_marker, end_marker) in BLOCKS.items():
        old_text = loaded.get("5.6.1", {}).get(rel)
        new_text = loaded.get("5.6.1-new", {}).get(rel)
        if old_text is None or new_text is None:
            report += [f"### {label}", "", "Diff unavailable: a source header is missing.", ""]
            continue
        old_block = block(old_text, start_marker, end_marker).splitlines()
        new_block = block(new_text, start_marker, end_marker).splitlines()
        delta = list(difflib.unified_diff(old_block, new_block,
            fromfile=f"5.6.1/{rel}:{label}", tofile=f"5.6.1-new/{rel}:{label}",
            lineterm="", n=3))
        report += [f"### {label}", "", chr(96) * 3 + "diff"]
        report += delta if delta else ["No textual difference in extracted block."]
        report += [chr(96) * 3, ""]

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"Wrote {args.output} ({args.output.stat().st_size:,} bytes)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
